static bool t2_emit_function(PirCodeEmitter *em, const PirModule *mod, const MFunc *mf) {
    T2AsmCtx *ctx = (T2AsmCtx *)em->ctx;
    FILE *out = ctx->out;
    const PirTargetSpec *target = ctx->target;
    const char *lp = pir_asm_lbl_pfx(target);

    /* Fold empty trampoline blocks (single MI_T2_B). */
    uint32_t nb = mf->blocks.len;
    uint32_t *blk_redir = nb ? (uint32_t *)malloc(nb * sizeof(uint32_t)) : NULL;
    bool     *blk_skip  = nb ? (bool *)calloc(nb, sizeof(bool)) : NULL;
    if (nb && (!blk_redir || !blk_skip)) abort();
    for (uint32_t b = 0u; b < nb; ++b) blk_redir[b] = b;
    for (uint32_t b = 1u; b < nb; ++b) {
        const MBlock *blk = &mf->blocks.data[b];
        if (blk->insts.len == 1u && blk->insts.data[0].op == MI_T2_B) {
            uint32_t tgt = blk->insts.data[0].ops[0].u.block_id;
            if (tgt != b) {
                blk_redir[b] = tgt;
                blk_skip[b]  = true;
            }
        }
    }
    for (uint32_t b = 0u; b < nb; ++b) {
        uint32_t cur = blk_redir[b];
        for (uint32_t hops = 0u; hops < nb && blk_redir[cur] != cur; ++hops) cur = blk_redir[cur];
        blk_redir[b] = cur;
    }
    ctx->blk_redir = blk_redir;

    /* ARM ELF requires %function (NOT @function, because @ starts a comment in ARM asm!)
     * and .thumb_func right before the function label so bit 0 is set on all relocations! */
    pir_asm_emit_section_directive(out, mod, target, mf->pir_fn->section,
                                   PIR_GSEG_DATA, false, false, true);
    pir_asm_emit_linkage(out, target, mf->pir_fn->linkage, mf->pir_fn->name, t2_needs_sym_quote);
    fputs("\t.type ", out);
    pir_asm_emit_sym(out, target, mf->pir_fn->name, NULL, t2_needs_sym_quote);
    fputs(", %function\n", out);
    fprintf(out, "\t.p2align 1\n");
    fprintf(out, "\t.thumb_func\n");
    pir_asm_emit_sym(out, target, mf->pir_fn->name, NULL, t2_needs_sym_quote);
    fputs(":\n\t.cfi_startproc\n", out);

    PirDwarfLocState loc_st = { 0u, false };
    for (uint32_t b = 0u; b < nb; ++b) {
        if (blk_skip[b]) continue;
        const MBlock *blk = &mf->blocks.data[b];
        if (b > 0u) fprintf(out, "%sF%u_B%u:\n", lp, mf->fn_index, b);
        for (uint32_t j = 0u; j < blk->insts.len; ++j) {
            const MInst *ins = &blk->insts.data[j];
            if (ins->op == MI_T2_B && j + 1u == blk->insts.len) {
                uint32_t next_b = b + 1u;
                while (next_b < nb && blk_skip[next_b]) next_b++;
                if (redir_blk(ctx, ins->ops[0].u.block_id) == next_b) continue;
            }
            pir_asm_emit_dwarf_loc(out, mod, mf->pir_fn, &loc_st, ins->loc_idx);
            emit_inst(ctx, mf, ins);
        }
    }

    fputs("\t.cfi_endproc\n\t.size ", out);
    pir_asm_emit_sym(out, target, mf->pir_fn->name, NULL, t2_needs_sym_quote);
    fputs(", .-", out);
    pir_asm_emit_sym(out, target, mf->pir_fn->name, NULL, t2_needs_sym_quote);
    fputs("\n\n", out);

    ctx->blk_redir = NULL;
    free(blk_redir);
    free(blk_skip);
    return true;
}

static bool t2_emit_globals(PirCodeEmitter *em, const PirModule *mod,
                            const PirTargetSpec *target) {
    T2AsmCtx *ctx = (T2AsmCtx *)em->ctx;
    return pir_asm_emit_globals(ctx->out, mod, target, t2_needs_sym_quote);
}

static bool t2_emit_footer(PirCodeEmitter *em, const PirModule *mod,
                           const PirTargetSpec *target) {
    T2AsmCtx *ctx = (T2AsmCtx *)em->ctx;
    return pir_asm_emit_module_footer(ctx->out, mod, target);
}

void pir_thumb2_asm_emitter_init(PirCodeEmitter *em, FILE *out, const PirTargetSpec *target) {
    T2AsmCtx *ctx = (T2AsmCtx *)calloc(1u, sizeof(T2AsmCtx));
    if (!ctx) abort();
    ctx->out    = out;
    ctx->target = target;

    em->ctx                = ctx;
    em->emit_module_header = t2_emit_header;
    em->emit_function      = t2_emit_function;
    em->emit_globals       = t2_emit_globals;
    em->emit_module_footer = t2_emit_footer;
}
